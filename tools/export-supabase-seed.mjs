#!/usr/bin/env node
// Turns data.js into the SQL that carries it into the Supabase database — the
// heart of `npm run migration`, which is how a beer added to data.js reaches
// the database the app and the live stats page read.
//
//   node tools/export-supabase-seed.mjs            # SQL to stdout
//   node tools/export-supabase-seed.mjs --out f.sql
//   node tools/export-supabase-seed.mjs --json f.json
//
// The JSON form is the same rows the REST API returns, which is what lets
// `npm run sync` be exercised without reaching the network — see
// tools/roundtrip-supabase.mjs.
//
// The SQL is the whole of data.js, written so that replaying it is safe:
//
//   - a row data.js knows is updated to say what data.js says — the file is
//     where entries are authored, so on a match, the file wins;
//   - a row data.js is missing is inserted;
//   - a row only the database knows — a beer logged through the app's own
//     form — is left exactly alone. Nothing here deletes.
//
// Beers are matched on name and date, breweries on name, places on city and
// country, everything else on its own key. Because every statement is a
// no-op once the database agrees with the file, each generated migration can
// carry the full dataset and cost nothing but the diff.
import { writeFileSync } from 'node:fs';
import { loadData } from './load-data.mjs';
import { toRows, TABLES } from '../public/stats/supabase-rows.mjs';

const arg = name => {
  const i = process.argv.indexOf(name);
  return i === -1 ? null : process.argv[i + 1];
};

const lit = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(lit).join(',')}]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

// Column types, so a VALUES list can be given one. Postgres reads an untyped
// literal in a VALUES row as `unknown` and will not compare it to a date or an
// integer; casting the first row is enough to type the whole list.
const TYPES = {
  seq: 'int', abv: 'numeric', rating: 'numeric', avg: 'numeric', untappd: 'numeric',
  lat: 'double precision', lng: 'double precision', is_new: 'boolean',
  drank_on: 'date', domains: 'text[]', aka: 'text[]',
};
const typeOf = col => TYPES[col] ?? 'text';

// The key that decides whether a row is already there.
const KEYS = {
  countries: ['cc'],
  locations: ['city', 'country'],
  breweries: ['name'],
  brand_domains: ['beer_name'],
  want_to_try: ['beer'],
  untappd_averages: ['beer_name'],
  app_meta: ['key'],
};

function valuesList(rows, cols) {
  return rows.map((r, i) => {
    const cells = cols.map(c => (i === 0 ? `${lit(r[c])}::${typeOf(c)}` : lit(r[c])));
    return `  (${cells.join(',')})`;
  }).join(',\n');
}

// An upsert: insert the rows that are missing, and set the listed columns on
// the ones already there — data.js is where entries are authored, so on a
// match the file's values win.
function upsert(table, rows, { update = [] } = {}) {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const key = KEYS[table];
  const action = update.length
    ? `do update set ${update.map(c => `${c} = excluded.${c}`).join(', ')}`
    : 'do nothing';
  return `insert into public.${table} (${cols.join(',')}) values\n` +
         `${valuesList(rows, cols)}\n` +
         `on conflict (${key.join(',')}) ${action};\n`;
}

// `beers` has no unique key — the same beer drunk twice is two rows, which is
// the point of the table — so it cannot use `on conflict`. A review is matched
// on its name and the month it was drunk, which is all data.js records anyway.
// On a match every other column follows the file; a review only the database
// knows is untouched.
function seedBeers(rows) {
  const cols = Object.keys(rows[0]);
  const list = valuesList(rows, cols);
  const insertCols = cols.join(',');
  const updatable = cols.filter(c => c !== 'name' && c !== 'drank_on');
  return `-- Reviews the file and the table share follow the file.
update public.beers b
   set ${updatable.map(c => `${c} = s.${c}`).join(',\n       ')}
  from (values\n${list}\n) as s(${insertCols})
 where b.name = s.name and b.drank_on = s.drank_on;

-- Reviews the file has that the table does not.
insert into public.beers (${insertCols})
select ${cols.map(c => `s.${c}`).join(',')}
  from (values\n${list}\n) as s(${insertCols})
 where not exists (
   select 1 from public.beers b where b.name = s.name and b.drank_on = s.drank_on
 );
`;
}

const rows = toRows(loadData());

if (arg('--json')) {
  writeFileSync(arg('--json'), JSON.stringify(rows, null, 2) + '\n');
  process.exit(0);
}

const sql = [
  '-- Generated by tools/export-supabase-seed.mjs — the whole of data.js as',
  '-- add-and-update SQL. Do not hand-edit; edit data.js and regenerate.',
  '--',
  '-- On a match the file wins; a row only the database knows is left alone;',
  '-- nothing deletes. Replaying it against a database that already agrees',
  '-- with the file changes nothing.',
  '',
  // A country has to exist before a brewery or a place can name it, and a
  // brewery before the beers that point at it.
  upsert('countries', rows.countries, { update: ['flag', 'name'] }),
  upsert('locations', rows.locations, { update: ['region', 'cc', 'lat', 'lng'] }),
  upsert('breweries', rows.breweries, {
    update: ['location', 'country', 'cc', 'lang', 'native_name', 'lat', 'lng'],
  }),
  seedBeers(rows.beers),
  upsert('brand_domains', rows.brand_domains, { update: ['domains', 'logo'] }),
  upsert('want_to_try', rows.want_to_try, {
    update: ['style', 'origin', 'abv', 'region', 'untappd', 'method', 'aka', 'seq'],
  }),
  upsert('untappd_averages', rows.untappd_averages, { update: ['avg'] }),
  upsert('app_meta', rows.app_meta, { update: ['value'] }),
].join('\n');

const out = arg('--out');
if (out) writeFileSync(out, sql);
else process.stdout.write(sql);

if (out) {
  const counts = TABLES.map(t => `${rows[t].length} ${t}`).join(' · ');
  console.log(`Wrote ${out} — ${counts}.`);
}
